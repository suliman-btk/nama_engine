#!/usr/bin/env python3
"""
Build one Lottie file per scene from the artist's "talking avatar" character,
with its mouth driven by REAL Rhubarb phoneme cues.

THE MOUTH PROBLEM AND THE FIX
-----------------------------
The source character's mouth ("Path 37", the white opening) animates through 48
path-morph keyframes, but those only ever use THREE distinct drawn shapes
(widths 16.6 / 23.4 / 31.1). Three shapes cannot represent speech — that is why
the lip sync read as wrong even when the timing was correct.

So we synthesise a full viseme set. Each of Rhubarb's mouth shapes gets its own
mouth, generated by scaling the artist's own widest shape horizontally and
vertically about its centre. Because every shape is derived from the original
artwork they all sit in the right place and keep the same flat-vector styling —
we are only opening and rounding the mouth the way a 2D animator would.

    A, X  closed         -> layer hidden, only the lip curve shows
    B     "ee"/consonant -> wide and nearly flat
    C     "eh"/"ay"      -> medium open
    D     "ah"           -> widest, tallest
    E     "oh"           -> narrow and rounded
    F     "oo"/W         -> narrowest, small round
    G     F/V            -> flat, teeth on lip
    H     L              -> small-medium open

Keyframes are emitted in PAIRS (hold the outgoing shape until SNAP frames before
the cue, then snap) so the mouth lands on each shape instead of easing mushily
between them. Every keyframe carries easing — a bare {t, s} keyframe mid-sequence
makes lottie-web drop the entire mouth group and the character renders with no
mouth at all.

Eye-blink and eyebrow keyframes are tiled so the character keeps blinking past the
source's 10s loop. The knit is recoloured cream so a light figure reads clearly
against the navy slides.

USAGE:  python build_avatar_lottie.py [lesson-number]      # default 01
OUT:    production/remotion-lesson-01/public/lottie/scenes/scene-XXX.json
        production/remotion-lesson-01/public/data/durations.json
"""
import sys, json, copy, subprocess
from pathlib import Path

LESSON_NUM = sys.argv[1] if len(sys.argv) > 1 else "01"
ACT_ROOT = Path("/Users/suilman_btk/Desktop/NAMA foundation /videos-ACT/act-video-course")
LESSON_DIR = ACT_ROOT / "lessons" / f"lesson-{LESSON_NUM}"
SRC_LOTTIE = ACT_ROOT / "production" / "remotion-lesson-01" / "public" / "lottie" / "talking-avatar.json"
AUDIO_DIR = LESSON_DIR / "audio" / "edge-raw"
VISEME_DIR = LESSON_DIR / "audio" / "edge-visemes"
PROJ = ACT_ROOT / "production" / "remotion-lesson-01"
OUT_DIR = PROJ / "public" / "lottie" / "scenes"
OUT_DIR.mkdir(parents=True, exist_ok=True)

MOUTH_LAYER_IND = 4          # "Path 37" - the animated white mouth-opening shape
EYE_LAYER_INDS = [18, 19]    # left eye / right eye (blink path morphs)
BROW_LAYER_IND = 7           # "Group 5" - eyebrow position drift
SRC_LOOP = 600               # source comp length in its own 60fps timebase

# (horizontal scale, vertical scale) applied to the artist's widest mouth.
# None => mouth closed (layer hidden).
VISEME_SCALE = {
    "X": None,
    "A": None,
    "B": (0.86, 0.30),
    "C": (0.92, 0.74),
    "D": (0.96, 1.28),
    "E": (0.60, 1.06),
    "F": (0.42, 0.86),
    "G": (0.82, 0.22),
    "H": (0.74, 0.60),
}
CLOSED = {"X", "A"}

RECOLOR = {
    "#58556C": "#E9E1CE",  # knit main
    "#383546": "#C9BEA4",  # knit shadow
    "#67627E": "#F6F1E4",  # knit highlight
}

SNAP = 1  # frames to move between mouth shapes — fast, then hold

# Blinks are re-authored rather than inherited. The source artwork's blink is a
# DOUBLE blink — its six keyframes go open, open, shut, open, shut, open, i.e. two
# closures inside 0.48s. Re-timed into 30fps that became a rapid flutter of the
# eyelashes. Replaced with a single human blink, and applied identically to both
# eyes so they can never drift out of step with each other.
#   (frame offset, which shape)
BLINK_CYCLE = [(0, "open"), (4, "closed"), (6, "closed"), (11, "open")]
BLINK_INTERVALS = [138, 174, 150, 204, 162, 186]  # ~4.6-6.8s apart, varied so it isn't metronomic

# The eyebrows are re-authored for the same reason as the blink. The source moves
# them down 5.25, overshoots up -2.75 and settles — the whole twitch inside 18
# frames (0.6s) — which reads as a nervous flicker. This is the same gesture at a
# little over a third of the speed, roughly half the travel, and far less often.
#   (frame offset, y offset)
BROW_CYCLE = [(0, 0.0), (18, 2.4), (38, -0.8), (58, 0.0)]
BROW_INTERVALS = [312, 396, 348, 432]  # ~10-14s apart

# The generated Lottie is authored at the VIDEO's frame rate, not the source
# artwork's 60fps. Remotion advances a Lottie one frame per composition frame, so
# a 60fps animation inside a 30fps composition plays at half speed and drifts
# badly out of sync with the audio. Authoring at the composition rate is correct
# under either interpretation of the runtime.
OUT_FPS = 30


def hex_to_rgba(h):
    h = h.lstrip("#")
    return [int(h[i:i+2], 16) / 255 for i in (0, 2, 4)] + [1]


def rgba_to_hex(c):
    return "#%02X%02X%02X" % tuple(round(x * 255) for x in c[:3])


def recolor(node):
    if isinstance(node, dict):
        if node.get("ty") in ("fl", "st"):
            ck = node.get("c", {}).get("k")
            if isinstance(ck, list) and len(ck) >= 3 and not isinstance(ck[0], dict):
                new = RECOLOR.get(rgba_to_hex(ck))
                if new:
                    node["c"]["k"] = hex_to_rgba(new)
        for v in node.values():
            recolor(v)
    elif isinstance(node, list):
        for v in node:
            recolor(v)


def scale_shape(shape, sx, sy):
    """Scale a Lottie bezier about its own centre. Vertices move; tangents (which
    are relative offsets, and which create this mouth's curvature) scale directly,
    so sy genuinely opens the mouth rather than just moving the corners."""
    out = copy.deepcopy(shape)
    xs = [v[0] for v in out["v"]]
    ys = [v[1] for v in out["v"]]
    cx = (min(xs) + max(xs)) / 2
    cy = (min(ys) + max(ys)) / 2
    dy = (sy - 1.0) * 2.6          # a taller mouth drops the jaw rather than growing symmetrically
    out["v"] = [[cx + (x - cx) * sx, cy + (y - cy) * sy + dy] for x, y in out["v"]]
    out["i"] = [[x * sx, y * sy] for x, y in out["i"]]
    out["o"] = [[x * sx, y * sy] for x, y in out["o"]]
    return out


def ease_pair(dims: int = 1):
    return {
        "i": {"x": [0.62] * dims, "y": [1] * dims},
        "o": {"x": [0.38] * dims, "y": [0] * dims},
    }


def shape_ease():
    return {"i": {"x": 0.62, "y": 1}, "o": {"x": 0.38, "y": 0}}


def tile_keyframes(kfs, total_frames, period, time_scale=1.0):
    """Repeat a keyframe list until total_frames is covered, rescaling the source
    times into the output frame rate so blinks keep their real-world speed."""
    if not kfs:
        return kfs
    out = []
    for r in range(int(total_frames // period) + 2):
        off = r * period
        for kf in kfs:
            k = copy.deepcopy(kf)
            k["t"] = round(kf["t"] * time_scale) + off
            if k["t"] > total_frames + period:
                break
            out.append(k)
    dedup = []
    for k in out:
        if dedup and k["t"] <= dedup[-1]["t"]:
            continue
        dedup.append(k)
    return dedup


def build_scene(base, cues, duration_s):
    d = copy.deepcopy(base)
    src_fps = d["fr"]
    time_scale = OUT_FPS / src_fps
    d["fr"] = OUT_FPS
    total = max(2, int(round(duration_s * OUT_FPS)))
    d["op"] = total
    d["ip"] = 0

    layers = {l["ind"]: l for l in d["layers"]}
    for l in d["layers"]:
        l["op"] = total
        l["ip"] = 0

    mouth = layers[MOUTH_LAYER_IND]
    ks = mouth["shapes"][0]["it"][0]["ks"]

    widest = max(
        (kf["s"][0] for kf in ks["k"] if isinstance(kf.get("s"), list) and isinstance(kf["s"][0], dict)),
        key=lambda s: max(v[0] for v in s["v"]) - min(v[0] for v in s["v"]),
    )

    # one drawn mouth per Rhubarb shape, all derived from the artist's own artwork
    SHAPES = {
        key: scale_shape(widest, *(sc if sc else VISEME_SCALE["B"]))
        for key, sc in VISEME_SCALE.items()
    }

    changes = []
    last = None
    for cue in cues:
        v = cue["value"] if cue["value"] in VISEME_SCALE else "B"
        t = int(round(cue["start"] * OUT_FPS))
        if t > total:
            break
        if v != last:
            changes.append((t, v))
            last = v

    shape_kfs, op_kfs = [], []

    def push(t, v):
        if shape_kfs and t <= shape_kfs[-1]["t"]:
            t = shape_kfs[-1]["t"] + 1
        shape_kfs.append({**shape_ease(), "t": t, "s": [copy.deepcopy(SHAPES[v])]})
        op_kfs.append({**ease_pair(1), "t": t, "s": [0 if v in CLOSED else 100]})

    if not changes:
        push(0, "X")
    else:
        push(changes[0][0], changes[0][1])
        for i in range(1, len(changes)):
            t, v = changes[i]
            push(max(t - SNAP, shape_kfs[-1]["t"] + 1), changes[i - 1][1])
            push(t, v)

    ks["a"] = 1
    ks["k"] = shape_kfs
    mouth["ks"]["o"] = {"a": 1, "k": op_kfs, "ix": 11}

    loop = max(2, int(round(SRC_LOOP * time_scale)))

    # --- re-author the blink so both eyes stay in lockstep and at a human rate ---
    for ind in EYE_LAYER_INDS:
        eks = layers[ind]["shapes"][0]["it"][0]["ks"]
        src = [kf["s"][0] for kf in eks["k"][:6]]
        if len(src) < 3:
            continue

        def eye_height(shape):
            ys = [v[1] for v in shape["v"]]
            return max(ys) - min(ys)

        open_shape = max(src, key=eye_height)     # eye at full height
        closed_shape = min(src, key=eye_height)   # eye squeezed shut
        shape_for = {"open": open_shape, "closed": closed_shape}

        kfs, t, i = [], 45, 0
        while t < total:
            for off, which in BLINK_CYCLE:
                ft = t + off
                if ft >= total:
                    break
                if kfs and ft <= kfs[-1]["t"]:
                    ft = kfs[-1]["t"] + 1
                kfs.append({**shape_ease(), "t": ft, "s": [copy.deepcopy(shape_for[which])]})
            t += BLINK_INTERVALS[i % len(BLINK_INTERVALS)]
            i += 1
        if kfs and kfs[-1]["t"] < total:
            kfs.append({**shape_ease(), "t": total, "s": [copy.deepcopy(open_shape)]})
        if kfs:
            eks["a"] = 1
            eks["k"] = kfs
    bp = layers[BROW_LAYER_IND]["ks"]["p"]
    if bp.get("a") == 1:
        base_xyz = bp["k"][0].get("s", [0, 0, 0])
        bx, by, bz = base_xyz[0], base_xyz[1], base_xyz[2] if len(base_xyz) > 2 else 0
        kfs, t, i = [], 150, 0
        while t < total:
            for off, dy in BROW_CYCLE:
                ft = t + off
                if ft >= total:
                    break
                if kfs and ft <= kfs[-1]["t"]:
                    ft = kfs[-1]["t"] + 1
                kfs.append({**ease_pair(3), "t": ft, "s": [bx, by + dy, bz]})
            t += BROW_INTERVALS[i % len(BROW_INTERVALS)]
            i += 1
        if kfs and kfs[-1]["t"] < total:
            kfs.append({**ease_pair(3), "t": total, "s": [bx, by, bz]})
        if kfs:
            bp["k"] = kfs

    recolor(d["layers"])
    return d


def main():
    base = json.load(open(SRC_LOTTIE))
    scenes = json.load(open(LESSON_DIR / "scenes.json"))
    durations = {}

    for i, sc in enumerate(scenes, 1):
        sid = sc["id"]
        r = subprocess.run(
            ["ffprobe", "-v", "error", "-show_entries", "format=duration",
             "-of", "default=noprint_wrappers=1:nokey=1", str(AUDIO_DIR / f"{sid}.wav")],
            capture_output=True, text=True, check=True)
        dur = float(r.stdout.strip())
        durations[sid] = dur

        cues = json.load(open(VISEME_DIR / f"{sid}.json"))["mouthCues"]
        out = build_scene(base, cues, dur)
        json.dump(out, open(OUT_DIR / f"{sid}.json", "w"), separators=(",", ":"))
        print(f"[{i}/{len(scenes)}] {sid}  {dur:6.2f}s  cues={len(cues)}", flush=True)

    json.dump(durations, open(PROJ / "public" / "data" / "durations.json", "w"), indent=2)
    json.dump(durations, open(PROJ / "src" / "data" / "durations.json", "w"), indent=2)
    total = sum(durations.values())
    print(f"\nTotal: {total:.1f}s = {total/60:.2f} min")


if __name__ == "__main__":
    main()
